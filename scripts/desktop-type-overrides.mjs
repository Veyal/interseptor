#!/usr/bin/env node
// desktop-type-overrides.mjs — regenerates internal/control/ui/css/desktop/type.css.
//
// The desktop skin allows font weights 400/500/600 only and no uppercase labels
// (docs/desktop-design.md). The web stylesheets set literal weights (550, 650,
// 700, 800) and text-transform:uppercase per component, so the desktop layer
// restates each of those selectors under html.desktop-app. Each selector keeps
// its own specificity plus (0,1,1), so it beats exactly the web rule it maps and
// nothing else. Run after a web stylesheet adds a bold or uppercase rule:
//
//   node scripts/desktop-type-overrides.mjs           (rewrite type.css)
//   node scripts/desktop-type-overrides.mjs --check   (exit 1 when stale)
import fs from 'node:fs';
import path from 'node:path';

const ui = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'internal', 'control', 'ui');
const index = fs.readFileSync(path.join(ui, 'index.html'), 'utf8');
const sheets = [...index.matchAll(/<link rel="stylesheet" href="\/([^"]+)">/g)].map((m) => m[1]).filter((p) => !p.startsWith('css/desktop/') && p !== 'desktop.css');

// rules walks a stylesheet and yields [selectorList, body] for style rules,
// descending into @media/@supports and skipping @keyframes and @font-face.
function* rules(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) return;
    const head = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    const body = css.slice(open + 1, j - 1);
    if (head.startsWith('@media') || head.startsWith('@supports') || head.startsWith('@container') || head.startsWith('@layer')) yield* rules(body);
    else if (!head.startsWith('@')) yield [head, body];
    i = j;
  }
}

const splitList = (s) => { const out = []; let d = 0, st = 0; for (let k = 0; k < s.length; k++) { const c = s[k]; if (c === '(') d++; else if (c === ')') d--; else if (c === ',' && !d) { out.push(s.slice(st, k)); st = k + 1; } } out.push(s.slice(st)); return out.map((x) => x.trim()).filter(Boolean); };
const scoped = (sel) => !/^(:root|html|body\b|\*)/.test(sel);

const w600 = new Set(), w500 = new Set(), caps = new Set();
for (const sheet of sheets) {
  for (const [head, body] of rules(fs.readFileSync(path.join(ui, sheet), 'utf8'))) {
    const fw = /(?:^|;)\s*font-weight\s*:\s*(\d+|bold)/.exec(body);
    const fs_ = /(?:^|;)\s*font\s*:\s*(\d{3}|bold)\s/.exec(body);
    const weight = fw ? fw[1] : fs_ ? fs_[1] : '';
    const sels = splitList(head).filter(scoped);
    if (['650', '700', '800', '900', 'bold'].includes(weight)) sels.forEach((s) => w600.add(s));
    if (weight === '550') sels.forEach((s) => w500.add(s));
    if (/text-transform\s*:\s*uppercase/.test(body)) sels.forEach((s) => caps.add(s));
  }
}
const block = (set, decl) => [...set].sort().map((s) => 'html.desktop-app ' + s).join(',\n') + '{' + decl + '}\n';
const out = `/* desktop/type.css — GENERATED by scripts/desktop-type-overrides.mjs; do not edit.
   Weights 400/500/600 only and sentence case on desktop: every web rule that sets
   650/700/800 reads 600, 550 reads 500, and uppercase-transformed labels render
   in their written case. */
${block(w600, 'font-weight:600')}${block(w500, 'font-weight:500')}${block(caps, 'text-transform:none;letter-spacing:normal')}`;
const target = path.join(ui, 'css', 'desktop', 'type.css');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== out) { console.error('css/desktop/type.css is stale; run node scripts/desktop-type-overrides.mjs'); process.exit(1); }
  console.log('type.css is current');
} else {
  fs.writeFileSync(target, out);
  console.log(`type.css: ${w600.size} bold, ${w500.size} medium, ${caps.size} uppercase selectors`);
}
